/**
 * Fast RFC4122 v4 compliant UUID generator for React Native.
 * Uses Math.random() as a fallback if cryptographically secure random is unavailable,
 * but designed for high performance in business applications.
 */
export const generateUUID = (): string => {
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    const v = c === 'x' ? r : (r & 0x3) | 0x8;
    return v.toString(16);
  });
};
